function iconFromUrl(url?: string) {
  if (!url || url === "#" || !url.startsWith("http")) return undefined;
  try {
    const host = new URL(url).hostname.replace(/^www\./, "");
    return `https://www.google.com/s2/favicons?sz=128&domain=${host}`;
  } catch {
    return undefined;
  }
}

function app(
  partial: Omit<AppEntry, "rating" | "ratingsCount" | "description"> & {
    rating?: number;
    ratingsCount?: number;
    description?: string;
  },
): AppEntry {
  const merged = {
    rating: 4.5,
    ratingsCount: 128,
    description: partial.tagline,
    platform: "Unknown",
    ...partial,
    iconUrl: partial.iconUrl || iconFromUrl(partial.url),
  };
  return {
    ...merged,
    provenance: inferProvenance(merged),
    roles: inferRoles(merged),
  };
}

