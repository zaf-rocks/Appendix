export function listingStatus(app: AppEntry): "live" | "dead" | "soon" {
  if (app.comingSoon) return "soon";
  if (!app.url || app.url === "#") return "dead";
  return "live";
}

export function isUp(app: AppEntry) {
  return listingStatus(app) === "live";
}

export function isLive(app: AppEntry) {
  return listingStatus(app) === "live";
}
